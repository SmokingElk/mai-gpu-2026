static void sphereVertex(double phi, double th)
{
    double cp = cos(phi);
    double x = cp * cos(th);
    double y = cp * sin(th);
    double z = sin(phi);
    glNormal3d(x, y, z);
    glTexCoord2d(th / (2.0 * kPi), (phi + kPi / 2.0) / kPi);
    glVertex3d(x, y, z);
}

static void buildSphereList(void)
{
    const int stacks = 12, slices = 18;
    g_sphereList = glGenLists(1);
    glNewList(g_sphereList, GL_COMPILE);
    glBegin(GL_QUADS);
    for (int st = 0; st < stacks; st++) {
        double phi0 = -kPi / 2.0 + kPi * st / stacks;
        double phi1 = -kPi / 2.0 + kPi * (st + 1) / stacks;
        for (int sl = 0; sl < slices; sl++) {
            double th0 = 2.0 * kPi * sl / slices;
            double th1 = 2.0 * kPi * (sl + 1) / slices;
            sphereVertex(phi0, th0);
            sphereVertex(phi0, th1);
            sphereVertex(phi1, th1);
            sphereVertex(phi1, th0);
        }
    }
    glEnd();
    glEndList();
}

static void makePerspective(double fovyDeg, double aspect, double znear, double zfar, float *m)
{
    double f = 1.0 / tan(fovyDeg * kDeg2Rad / 2.0);
    memset(m, 0, 16 * sizeof(float));
    m[0] = (float)(f / aspect);
    m[5] = (float)f;
    m[10] = (float)((zfar + znear) / (znear - zfar));
    m[11] = -1.0f;
    m[14] = (float)(2.0 * zfar * znear / (znear - zfar));
}

static void makeLookAt(double ex, double ey, double ez,
                       double cx, double cy, double cz,
                       double ux, double uy, double uz, float *m)
{
    double fx = cx - ex, fy = cy - ey, fz = cz - ez;
    double fl = sqrt(fx * fx + fy * fy + fz * fz);
    fx /= fl; fy /= fl; fz /= fl;
    double sx = fy * uz - fz * uy;
    double sy = fz * ux - fx * uz;
    double sz = fx * uy - fy * ux;
    double sl = sqrt(sx * sx + sy * sy + sz * sz);
    sx /= sl; sy /= sl; sz /= sl;
    double tx = sy * fz - sz * fy;
    double ty = sz * fx - sx * fz;
    double tz = sx * fy - sy * fx;
    m[0] = (float)sx;  m[1] = (float)tx;  m[2] = (float)-fx; m[3] = 0.0f;
    m[4] = (float)sy;  m[5] = (float)ty;  m[6] = (float)-fy; m[7] = 0.0f;
    m[8] = (float)sz;  m[9] = (float)tz;  m[10] = (float)-fz; m[11] = 0.0f;
    m[12] = (float)-(sx * ex + sy * ey + sz * ez);
    m[13] = (float)-(tx * ex + ty * ey + tz * ez);
    m[14] = (float)(fx * ex + fy * ey + fz * ez);
    m[15] = 1.0f;
}

