__device__ __forceinline__ double cube3(double x)
{
    return x * x * x;
}

__global__ void physicsKernel(const double4 *src, double4 *dst, double4 *vel, int n,
                              double3 cam, double3 bullet, int bulletActive)
{
    int i = blockIdx.x * blockDim.x + threadIdx.x;
    if (i >= n)
        return;
    double4 p = src[i];
    double4 v = vel[i];
    double ax = 0.0, ay = 0.0, az = 0.0;

    /* отталкивание от остальных частиц */
    for (int j = 0; j < n; j++) {
        if (j == i)
            continue;
        double4 q = src[j];
        double dx = p.x - q.x;
        double dy = p.y - q.y;
        double dz = p.z - q.z;
        double l = sqrt(dx * dx + dy * dy + dz * dz);
        double denom = l * l * l + EPS;
        ax += Q_PART * dx / denom;
        ay += Q_PART * dy / denom;
        az += Q_PART * dz / denom;
    }

    /* отталкивание от стенок куба (по каждой оси свое слагаемое) */
    double t;
    t = p.x - A_HALF;
    ax += Q_PART * t / (cube3(fabs(t)) + EPS);
    t = p.x + A_HALF;
    ax += Q_PART * t / (cube3(fabs(t)) + EPS);
    t = p.y - A_HALF;
    ay += Q_PART * t / (cube3(fabs(t)) + EPS);
    t = p.y + A_HALF;
    ay += Q_PART * t / (cube3(fabs(t)) + EPS);
    t = p.z - 2.0 * A_HALF;
    az += Q_PART * t / (cube3(fabs(t)) + EPS);
    t = p.z;
    az += Q_PART * t / (cube3(fabs(t)) + EPS);

    /* отталкивание от игрока (камеры) */
    double dx = p.x - cam.x;
    double dy = p.y - cam.y;
    double dz = p.z - cam.z;
    double l = sqrt(dx * dx + dy * dy + dz * dz);
    double denom = l * l * l + EPS;
    ax += Q_CAM * dx / denom;
    ay += Q_CAM * dy / denom;
    az += Q_CAM * dz / denom;

    /* отталкивание от пули */
    if (bulletActive) {
        dx = p.x - bullet.x;
        dy = p.y - bullet.y;
        dz = p.z - bullet.z;
        l = sqrt(dx * dx + dy * dy + dz * dz);
        denom = l * l * l + EPS;
        ax += Q_BUL * dx / denom;
        ay += Q_BUL * dy / denom;
        az += Q_BUL * dz / denom;
    }

    v.x = W_DAMP * v.x + K_FORCE * Q_PART * ax * DT;
    v.y = W_DAMP * v.y + K_FORCE * Q_PART * ay * DT;
    v.z = W_DAMP * v.z + K_FORCE * Q_PART * az * DT - G_GRAV * DT;
    p.x += v.x * DT;
    p.y += v.y * DT;
    p.z += v.z * DT;

    dst[i] = p;
    vel[i] = v;
}

__global__ void fieldKernel(uchar4 *out, int np, const double4 *pos, int n,
                            double3 bullet, int bulletActive)
{
    int strideX = gridDim.x * blockDim.x;
    int strideY = gridDim.y * blockDim.y;
    for (int j = blockIdx.y * blockDim.y + threadIdx.y; j < np; j += strideY) {
        for (int i = blockIdx.x * blockDim.x + threadIdx.x; i < np; i += strideX) {
            double x = (2.0 * (double)i / (double)(np - 1) - 1.0) * A_HALF;
            double y = (2.0 * (double)j / (double)(np - 1) - 1.0) * A_HALF;
            double E = 0.0;
            for (int p = 0; p < n; p++) {
                double dx = pos[p].x - x;
                double dy = pos[p].y - y;
                double dz = pos[p].z - SHIFT_Z;
                E += Q_PART / sqrt(dx * dx + dy * dy + dz * dz + EPS);
            }
            if (bulletActive) {
                double dx = bullet.x - x;
                double dy = bullet.y - y;
                double dz = bullet.z - SHIFT_Z;
                E += Q_BUL / sqrt(dx * dx + dy * dy + dz * dz + EPS);
            }
            E *= K_FORCE;
            int b = (int)E;
            if (b > 255)
                b = 255;
            if (b < 0)
                b = 0;
            out[(long long)j * np + i] = make_uchar4(0, 0, (unsigned char)b, 255);
        }
    }
}

