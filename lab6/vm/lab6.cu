static void failf(const char *fmt, ...)
{
    va_list ap;
    fputs("ERROR: ", stderr);
    va_start(ap, fmt);
    vfprintf(stderr, fmt, ap);
    va_end(ap);
    fputc('\n', stderr);
    exit(0);
}

static void fail(const char *msg)
{
    failf("%s", msg);
}

static void checkCuda(cudaError_t err, const char *what)
{
    if (err != cudaSuccess)
        failf("%s: %s", what, cudaGetErrorString(err));
}

static void checkGl(const char *what)
{
    GLenum e = glGetError();
    if (e != GL_NO_ERROR)
        failf("%s: GL error 0x%x", what, (int)e);
}

