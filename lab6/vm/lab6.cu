static pfn_eglGetError eglGetError;
static pfn_eglGetConfigAttrib eglGetConfigAttrib;

static void *g_eglLib = NULL;
static EGLDisplay g_dpy = NULL;
static EGLContext g_ctx = NULL;

static void *eglSym(void *lib, const char *name)
{
    void *p = dlsym(lib, name);
    if (p == NULL && eglGetProcAddress != NULL)
        p = eglGetProcAddress(name);
    if (p == NULL)
        failf("dlsym %s failed", name);
    return p;
}

static void initEgl(void)
{
    g_eglLib = dlopen("libEGL.so.1", RTLD_NOW | RTLD_GLOBAL);
    if (g_eglLib == NULL)
        failf("cannot load libEGL.so.1: %s", dlerror());

    eglGetProcAddress = (pfn_eglGetProcAddress)dlsym(g_eglLib, "eglGetProcAddress");
    if (eglGetProcAddress == NULL)
        failf("dlsym eglGetProcAddress failed: %s", dlerror());

    eglInitialize = (pfn_eglInitialize)eglSym(g_eglLib, "eglInitialize");
    eglTerminate = (pfn_eglTerminate)eglSym(g_eglLib, "eglTerminate");
    eglQueryString = (pfn_eglQueryString)eglSym(g_eglLib, "eglQueryString");
    eglQueryDevicesEXT = (pfn_eglQueryDevicesEXT)eglSym(g_eglLib, "eglQueryDevicesEXT");
    eglGetPlatformDisplayEXT = (pfn_eglGetPlatformDisplayEXT)eglSym(g_eglLib, "eglGetPlatformDisplayEXT");
    eglChooseConfig = (pfn_eglChooseConfig)eglSym(g_eglLib, "eglChooseConfig");
    eglBindAPI = (pfn_eglBindAPI)eglSym(g_eglLib, "eglBindAPI");
    eglCreateContext = (pfn_eglCreateContext)eglSym(g_eglLib, "eglCreateContext");
    eglCreatePbufferSurface = (pfn_eglCreatePbufferSurface)eglSym(g_eglLib, "eglCreatePbufferSurface");
    eglMakeCurrent = (pfn_eglMakeCurrent)eglSym(g_eglLib, "eglMakeCurrent");
    eglGetError = (pfn_eglGetError)eglSym(g_eglLib, "eglGetError");
    eglGetConfigAttrib = (pfn_eglGetConfigAttrib)eglSym(g_eglLib, "eglGetConfigAttrib");

    EGLDeviceEXT devs[16];
    EGLint ndev = 0;
    if (!eglQueryDevicesEXT(16, devs, &ndev))
        fail("eglQueryDevicesEXT failed");
    if (ndev < 1)
        fail("no EGL devices found");
    fprintf(stderr, "INFO: EGL devices found: %d\n", (int)ndev);

    /* варианты атрибутов для eglChooseConfig: от полного к минимальному */
    static const EGLint cfgVariants[][16] = {
        { EGL_SURFACE_TYPE, EGL_PBUFFER_BIT, EGL_RENDERABLE_TYPE, EGL_OPENGL_BIT,
          EGL_RED_SIZE, 8, EGL_GREEN_SIZE, 8, EGL_BLUE_SIZE, 8, EGL_ALPHA_SIZE, 8,
          EGL_DEPTH_SIZE, 24, EGL_NONE },
        { EGL_SURFACE_TYPE, EGL_PBUFFER_BIT, EGL_RENDERABLE_TYPE, EGL_OPENGL_BIT,
          EGL_RED_SIZE, 8, EGL_GREEN_SIZE, 8, EGL_BLUE_SIZE, 8,
          EGL_DEPTH_SIZE, 24, EGL_NONE },
        { EGL_SURFACE_TYPE, EGL_PBUFFER_BIT, EGL_RENDERABLE_TYPE, EGL_OPENGL_BIT, EGL_NONE },
        { EGL_RENDERABLE_TYPE, EGL_OPENGL_BIT, EGL_NONE },
        { EGL_SURFACE_TYPE, EGL_PBUFFER_BIT, EGL_NONE },
        { EGL_NONE },
    };
    const int numVariants = (int)(sizeof(cfgVariants) / sizeof(cfgVariants[0]));
    EGLint surfAttrs[] = { EGL_WIDTH, IMG_W, EGL_HEIGHT, IMG_H, EGL_NONE };

    /* первый проход — устройство NVIDIA, второй — любое */
    for (int pass = 0; pass < 2 && g_ctx == NULL; pass++) {
        for (int i = 0; i < ndev; i++) {
            fprintf(stderr, "INFO: EGL device %d (pass %d):\n", i, pass);
            EGLDisplay d = eglGetPlatformDisplayEXT(EGL_PLATFORM_DEVICE_EXT, devs[i], NULL);
            if (d == NULL) {
                fprintf(stderr, "INFO:   eglGetPlatformDisplayEXT failed, err 0x%x\n",
                        (unsigned)eglGetError());
                continue;
            }
            EGLint maj = 0, min = 0;
            if (!eglInitialize(d, &maj, &min)) {
                fprintf(stderr, "INFO:   eglInitialize failed, err 0x%x\n",
                        (unsigned)eglGetError());
                eglTerminate(d);
                continue;
            }
            const char *vendor = eglQueryString(d, EGL_VENDOR);
            fprintf(stderr, "INFO:   vendor: %s\n", vendor != NULL ? vendor : "(null)");
            int isNv = vendor != NULL && strstr(vendor, "NVIDIA") != NULL;
            if (pass == 0 && !isNv) {
                eglTerminate(d);
                continue;
            }
            if (!eglBindAPI(EGL_OPENGL_API)) {
                fprintf(stderr, "INFO:   eglBindAPI failed, err 0x%x\n",
                        (unsigned)eglGetError());
                eglTerminate(d);
                continue;
            }

            /* перебор вариантов атрибутов конфига */
            EGLConfig chosen = NULL;
            EGLConfig fallbackCfg = NULL;
            for (int v = 0; v < numVariants; v++) {
                EGLConfig cfg = NULL;
                EGLint ncfg = 0;
                if (!eglChooseConfig(d, cfgVariants[v], &cfg, 1, &ncfg)) {
                    fprintf(stderr, "INFO:   cfg variant %d: eglChooseConfig failed, err 0x%x\n",
                            v, (unsigned)eglGetError());
                    continue;
                }
                if (ncfg < 1) {
                    fprintf(stderr, "INFO:   cfg variant %d: no matching config\n", v);
                    continue;
                }
                EGLint depth = 0, surfType = 0;
                eglGetConfigAttrib(d, cfg, EGL_DEPTH_SIZE, &depth);
                eglGetConfigAttrib(d, cfg, EGL_SURFACE_TYPE, &surfType);
                fprintf(stderr, "INFO:   cfg variant %d: ok (depth %d, surface type 0x%x)\n",
                        v, (int)depth, (unsigned)surfType);
                if (depth >= 16 && (surfType & EGL_PBUFFER_BIT)) {
                    chosen = cfg;
                    break;
                }
                if (fallbackCfg == NULL)
                    fallbackCfg = cfg;
            }
            if (chosen == NULL && fallbackCfg != NULL) {
                chosen = fallbackCfg;
                fprintf(stderr, "WARN:   using config without depth buffer or pbuffer\n");
            }
            if (chosen == NULL) {
                eglTerminate(d);
                continue;
            }

            EGLContext ctx = eglCreateContext(d, chosen, NULL, NULL);
            if (ctx == NULL) {
                fprintf(stderr, "INFO:   eglCreateContext failed, err 0x%x\n",
                        (unsigned)eglGetError());
                eglTerminate(d);
                continue;
            }
            EGLSurface surf = eglCreatePbufferSurface(d, chosen, surfAttrs);
            if (surf != NULL) {
                if (!eglMakeCurrent(d, surf, surf, ctx)) {
                    fprintf(stderr, "INFO:   eglMakeCurrent(pbuffer) failed, err 0x%x\n",
                            (unsigned)eglGetError());
                    eglTerminate(d);
                    continue;
                }
                fprintf(stderr, "INFO:   surface: pbuffer\n");
            } else {
                fprintf(stderr, "INFO:   eglCreatePbufferSurface failed, err 0x%x, trying surfaceless\n",
                        (unsigned)eglGetError());
                if (!eglMakeCurrent(d, NULL, NULL, ctx)) {
                    fprintf(stderr, "INFO:   eglMakeCurrent(surfaceless) failed, err 0x%x\n",
                            (unsigned)eglGetError());
                    eglTerminate(d);
                    continue;
                }
                fprintf(stderr, "INFO:   surface: surfaceless\n");
            }
            g_dpy = d;
            g_ctx = ctx;
            break;
        }
    }
    if (g_ctx == NULL)
        fail("failed to create EGL OpenGL context");
}

