/*
 * Лабораторная работа № 6.
 * Моделирование и визуализация системы N взаимодействующих тел
 * с использованием технологий OpenGL и CUDA (vbo + texture).
 *
 * Управление мышью и клавиатурой в реальном времени НЕ реализовано,
 * так как программа запускается на удаленной ВМ без дисплея:
 * все действия игрока (перемещение, повороты камеры, выстрел)
 * программируются во входной строке перед запуском.
 *
 * Ввод (stdin): одна строка — последовательность команд через ';', например:
 *   left,30;forward,20;up,10;yaw,45;pitch,15;shoot,1;time,5
 * Команды (значение после запятой — число):
 *   left,right,forward,back,up,down,D — сдвиг камеры на D единиц
 *     (forward/back — по направлению взгляда, left/right — горизонтально
 *      перпендикулярно взгляду, up/down — вдоль оси z);
 *   yaw,deg   — поворот камеры в плоскости xy (параллельно полу);
 *   pitch,deg — наклон камеры: положительный угол смотрит вверх;
 *   shoot,1   — выстрел заряженной частицей по направлению взгляда;
 *   time,T    — моделирование T секунд (T/dt шагов); команд time может
 *               быть несколько (например, дать системе устояться, затем
 *               выстрелить и промоделировать еще).
 * После выполнения всех команд программа один раз рисует кадр — вид из камеры.
 *
 * Вывод (stdout): 8 байт (ширина, высота, little-endian) + пиксели RGBA.
 * При любой ошибке печатает "ERROR: ..." в stderr и завершается с кодом 0.
 *
 * Компиляция (чекер):
 *   nvcc -Werror cross-execution-space-call -lm -lcublas -lcurand -lGL -lGLU -lglut -lGLEW
 * Компиляция на ВМ без дисплея (нет libGLU/libglut/libGLEW, есть libEGL.so.1):
 *   nvcc -Werror cross-execution-space-call -lm -lGL
 *
 * GL-контекст создается через EGL на устройстве NVIDIA без X-сервера
 * (заголовков EGL на ВМ нет, поэтому функции EGL загружаются через dlopen).
 */

