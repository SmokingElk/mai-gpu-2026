    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA8, FIELD_NP, FIELD_NP, 0, GL_RGBA, GL_UNSIGNED_BYTE, NULL);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);

    glGenTextures(1, &g_sphereTex);
    glBindTexture(GL_TEXTURE_2D, g_sphereTex);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA8, TEX_SIZE, TEX_SIZE, 0, GL_RGBA, GL_UNSIGNED_BYTE, sphereTexData);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_REPEAT);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_REPEAT);
    glBindTexture(GL_TEXTURE_2D, 0);

    buildSphereList();

    glGenBuffers(1, &g_vbo);
    glBindBuffer(GL_ARRAY_BUFFER, g_vbo);
    glBufferData(GL_ARRAY_BUFFER, (long)(N_PART * sizeof(double4)), NULL, GL_DYNAMIC_DRAW);
    glBindBuffer(GL_ARRAY_BUFFER, 0);

    glGenBuffers(1, &g_pbo);
    glBindBuffer(GL_PIXEL_UNPACK_BUFFER, g_pbo);
    glBufferData(GL_PIXEL_UNPACK_BUFFER, (long)FIELD_NP * FIELD_NP * 4, NULL, GL_STREAM_DRAW);
    glBindBuffer(GL_PIXEL_UNPACK_BUFFER, 0);

    /* FBO для offscreen-рендера: работает и с pbuffer-, и с surfaceless-контекстом */
    glGenFramebuffers(1, &g_fbo);
    glBindFramebuffer(GL_FRAMEBUFFER, g_fbo);
    glGenRenderbuffers(1, &g_colorRb);
    glBindRenderbuffer(GL_RENDERBUFFER, g_colorRb);
    glRenderbufferStorage(GL_RENDERBUFFER, GL_RGBA8, IMG_W, IMG_H);
    glFramebufferRenderbuffer(GL_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, GL_RENDERBUFFER, g_colorRb);
    glGenRenderbuffers(1, &g_depthRb);
    glBindRenderbuffer(GL_RENDERBUFFER, g_depthRb);
    glRenderbufferStorage(GL_RENDERBUFFER, GL_DEPTH_COMPONENT24, IMG_W, IMG_H);
    glFramebufferRenderbuffer(GL_FRAMEBUFFER, GL_DEPTH_ATTACHMENT, GL_RENDERBUFFER, g_depthRb);
    if (glCheckFramebufferStatus(GL_FRAMEBUFFER) != GL_FRAMEBUFFER_COMPLETE)
        fail("FBO is not complete");

    checkGl("OpenGL init");
    fprintf(stderr, "INFO: GL %s | %s\n",
            (const char *)glGetString(GL_VERSION),
            (const char *)glGetString(GL_RENDERER));
}

/* ---------- инициализация CUDA и interop ---------- */

static void initCuda(void)
{
    int devCount = 0;
    checkCuda(cudaGetDeviceCount(&devCount), "cudaGetDeviceCount");
    if (devCount < 1)
        fail("no CUDA device available");
    checkCuda(cudaSetDevice(0), "cudaSetDevice");

    g_hPos = (double4 *)malloc(N_PART * sizeof(double4));
    g_hField = (unsigned char *)malloc((size_t)FIELD_NP * FIELD_NP * 4);
    if (g_hPos == NULL || g_hField == NULL)
        fail("out of memory");

    /* начальные положения частиц: x,y в (-a,a), z в (0,2a), скорости нулевые */
    srand(123456789);
    for (int i = 0; i < N_PART; i++) {
        g_hPos[i].x = -A_HALF + 2.0 * A_HALF * rand() / RAND_MAX;
        g_hPos[i].y = -A_HALF + 2.0 * A_HALF * rand() / RAND_MAX;
        g_hPos[i].z = 2.0 * A_HALF * rand() / RAND_MAX;
        g_hPos[i].w = 0.0;
    }

    checkCuda(cudaMalloc((void **)&g_dPosA, N_PART * sizeof(double4)), "cudaMalloc dPosA");
    checkCuda(cudaMalloc((void **)&g_dPosB, N_PART * sizeof(double4)), "cudaMalloc dPosB");
    checkCuda(cudaMalloc((void **)&g_dVel, N_PART * sizeof(double4)), "cudaMalloc dVel");
    checkCuda(cudaMalloc((void **)&g_dField, (size_t)FIELD_NP * FIELD_NP * 4), "cudaMalloc dField");
    checkCuda(cudaMemcpy(g_dPosA, g_hPos, N_PART * sizeof(double4), cudaMemcpyHostToDevice),
              "upload initial positions");
    checkCuda(cudaMemset(g_dVel, 0, N_PART * sizeof(double4)), "init velocities");

    /* попытка зарегистрировать VBO и PBO для CUDA-GL interop */
    cudaError_t e1 = cudaGraphicsGLRegisterBuffer(&g_vboRes, g_vbo, cudaGraphicsMapFlagsWriteDiscard);
    cudaError_t e2 = cudaGraphicsGLRegisterBuffer(&g_pboRes, g_pbo, cudaGraphicsMapFlagsWriteDiscard);
    if (e1 == cudaSuccess && e2 == cudaSuccess) {
        g_interop = 1;
    } else {
        if (e1 == cudaSuccess)
            cudaGraphicsUnregisterResource(g_vboRes);
        if (e2 == cudaSuccess)
            cudaGraphicsUnregisterResource(g_pboRes);
        g_vboRes = NULL;
        g_pboRes = NULL;
        cudaGetLastError();
        fprintf(stderr, "WARN: CUDA-GL interop unavailable (%s), using copy fallback\n",
                cudaGetErrorString(e1 != cudaSuccess ? e1 : e2));
    }
    fprintf(stderr, "INFO: interop %s\n", g_interop ? "ON (vbo+pbo)" : "OFF (copy)");
}

/* ---------- моделирование ---------- */

static void simulateSteps(int steps)
{
    if (steps <= 0)
        return;

    double4 *read = g_dPosA;
    double4 *write = NULL;
    if (g_interop) {
        checkCuda(cudaGraphicsMapResources(1, &g_vboRes, 0), "map vbo");
        size_t bytes = 0;
        checkCuda(cudaGraphicsResourceGetMappedPointer((void **)&write, &bytes, g_vboRes),
                  "get mapped vbo pointer");
    } else {
        write = g_dPosB;
    }

    double3 cam = g_cam;
    for (int s = 0; s < steps; s++) {
        if (g_bulletActive) {
            g_bulletPos.x += g_bulletVel.x * DT;
            g_bulletPos.y += g_bulletVel.y * DT;
            g_bulletPos.z += g_bulletVel.z * DT;
        }
        physicsKernel<<<PHYS_GRID, PHYS_BLOCK>>>(read, write, g_dVel, N_PART,
                                                 cam, g_bulletPos, g_bulletActive);
        checkCuda(cudaGetLastError(), "physicsKernel launch");
        double4 *tmp = read;
        read = write;
        write = tmp;
    }
    checkCuda(cudaDeviceSynchronize(), "cudaDeviceSynchronize");

    /* итоговые позиции оказались в read — нормализуем в g_dPosA */
    if (read != g_dPosA)
        checkCuda(cudaMemcpy(g_dPosA, read, N_PART * sizeof(double4), cudaMemcpyDeviceToDevice),
                  "copy positions");

    if (g_interop)
        checkCuda(cudaGraphicsUnmapResources(1, &g_vboRes, 0), "unmap vbo");
}

/* ---------- карта напряженности ---------- */

static void updateField(void)
{
    uchar4 *fieldPtr = NULL;
    if (g_interop) {
        checkCuda(cudaGraphicsMapResources(1, &g_pboRes, 0), "map pbo");
        size_t bytes = 0;
        checkCuda(cudaGraphicsResourceGetMappedPointer((void **)&fieldPtr, &bytes, g_pboRes),
                  "get mapped pbo pointer");
    } else {
        fieldPtr = g_dField;
    }

    fieldKernel<<<dim3(FIELD_GX, FIELD_GY), dim3(FIELD_BX, FIELD_BY)>>>(
        fieldPtr, FIELD_NP, g_dPosA, N_PART, g_bulletPos, g_bulletActive);
    checkCuda(cudaGetLastError(), "fieldKernel launch");
    checkCuda(cudaDeviceSynchronize(), "cudaDeviceSynchronize");

    glBindTexture(GL_TEXTURE_2D, g_fieldTex);
    if (g_interop) {
        checkCuda(cudaGraphicsUnmapResources(1, &g_pboRes, 0), "unmap pbo");
        glBindBuffer(GL_PIXEL_UNPACK_BUFFER, g_pbo);
        glTexSubImage2D(GL_TEXTURE_2D, 0, 0, 0, FIELD_NP, FIELD_NP, GL_RGBA, GL_UNSIGNED_BYTE, NULL);
        glBindBuffer(GL_PIXEL_UNPACK_BUFFER, 0);
    } else {
        checkCuda(cudaMemcpy(g_hField, g_dField, (size_t)FIELD_NP * FIELD_NP * 4, cudaMemcpyDeviceToHost),
                  "download field");
        glTexSubImage2D(GL_TEXTURE_2D, 0, 0, 0, FIELD_NP, FIELD_NP, GL_RGBA, GL_UNSIGNED_BYTE, g_hField);
    }
    checkGl("field texture update");
}

/* ---------- рендер кадра ---------- */

static void renderFrame(void)
{
    glBindFramebuffer(GL_FRAMEBUFFER, g_fbo);

    float proj[16], view[16];
    makePerspective(60.0, (double)IMG_W / (double)IMG_H, 0.1, 500.0, proj);
    double dx = cos(g_yawRad) * cos(g_pitchRad);
    double dy = sin(g_yawRad) * cos(g_pitchRad);
    double dz = sin(g_pitchRad);
    makeLookAt(g_cam.x, g_cam.y, g_cam.z,
               g_cam.x + dx, g_cam.y + dy, g_cam.z + dz,
               0.0, 0.0, 1.0, view);

    glMatrixMode(GL_PROJECTION);
    glLoadMatrixf(proj);
    glMatrixMode(GL_MODELVIEW);
    glLoadMatrixf(view);

    GLfloat lpos[4] = { -0.2f, -0.6f, 0.75f, 0.0f };
    GLfloat lamb[4] = { 0.3f, 0.3f, 0.3f, 1.0f };
    GLfloat ldif[4] = { 0.8f, 0.8f, 0.8f, 1.0f };
    glLightfv(GL_LIGHT0, GL_POSITION, lpos);
    glLightfv(GL_LIGHT0, GL_AMBIENT, lamb);
    glLightfv(GL_LIGHT0, GL_DIFFUSE, ldif);

    glClearColor(0.04f, 0.05f, 0.09f, 1.0f);
    glClear(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT);

    GLfloat A = (GLfloat)A_HALF;
    GLfloat Z = (GLfloat)(2.0 * A_HALF);

    /* ребра куба */
    glDisable(GL_LIGHTING);
    glDisable(GL_TEXTURE_2D);
    glColor3f(0.85f, 0.85f, 0.85f);
    glBegin(GL_LINES);
    glVertex3f(-A, -A, 0.0f); glVertex3f(A, -A, 0.0f);
    glVertex3f(A, -A, 0.0f);  glVertex3f(A, A, 0.0f);
    glVertex3f(A, A, 0.0f);   glVertex3f(-A, A, 0.0f);
    glVertex3f(-A, A, 0.0f);  glVertex3f(-A, -A, 0.0f);
    glVertex3f(-A, -A, Z); glVertex3f(A, -A, Z);
    glVertex3f(A, -A, Z);  glVertex3f(A, A, Z);
    glVertex3f(A, A, Z);   glVertex3f(-A, A, Z);
    glVertex3f(-A, A, Z);  glVertex3f(-A, -A, Z);
    glVertex3f(-A, -A, 0.0f); glVertex3f(-A, -A, Z);
    glVertex3f(A, -A, 0.0f);  glVertex3f(A, -A, Z);
    glVertex3f(A, A, 0.0f);   glVertex3f(A, A, Z);
    glVertex3f(-A, A, 0.0f);  glVertex3f(-A, A, Z);
    glEnd();

    /* пол — карта напряженности */
    glColor3f(1.0f, 1.0f, 1.0f);
    glEnable(GL_TEXTURE_2D);
    glBindTexture(GL_TEXTURE_2D, g_fieldTex);
    glBegin(GL_QUADS);
    glTexCoord2f(0.0f, 0.0f); glVertex3f(-A, -A, 0.0f);
    glTexCoord2f(1.0f, 0.0f); glVertex3f(A, -A, 0.0f);
    glTexCoord2f(1.0f, 1.0f); glVertex3f(A, A, 0.0f);
    glTexCoord2f(0.0f, 1.0f); glVertex3f(-A, A, 0.0f);
    glEnd();

    /* частицы — текстурированные сферы */
    glEnable(GL_LIGHTING);
    glBindTexture(GL_TEXTURE_2D, g_sphereTex);
    glColor3f(1.0f, 1.0f, 1.0f);
    for (int i = 0; i < N_PART; i++) {
        glPushMatrix();
        glTranslatef((float)g_hPos[i].x, (float)g_hPos[i].y, (float)g_hPos[i].z);
        glScalef(0.5f, 0.5f, 0.5f);
        glCallList(g_sphereList);
        glPopMatrix();
    }

    /* пуля */
    if (g_bulletActive) {
        glDisable(GL_TEXTURE_2D);
        glColor3f(1.0f, 0.25f, 0.15f);
        glPushMatrix();
        glTranslatef((float)g_bulletPos.x, (float)g_bulletPos.y, (float)g_bulletPos.z);
        glScalef(0.4f, 0.4f, 0.4f);
        glCallList(g_sphereList);
        glPopMatrix();
    }

    glDisable(GL_LIGHTING);
    glDisable(GL_TEXTURE_2D);
}

/* ---------- вывод кадра в stdout ---------- */

static void writeLE32(FILE *f, long long v)
{
    unsigned char b[4];
    b[0] = (unsigned char)(v & 0xFF);
    b[1] = (unsigned char)((v >> 8) & 0xFF);
    b[2] = (unsigned char)((v >> 16) & 0xFF);
    b[3] = (unsigned char)((v >> 24) & 0xFF);
    if (fwrite(b, 1, 4, f) != 4)
        fail("failed to write image header");
}

static void writeOutput(void)
{
    size_t pxBytes = (size_t)IMG_W * IMG_H * 4;
    size_t row = (size_t)IMG_W * 4;
    unsigned char *px = (unsigned char *)malloc(pxBytes);
    unsigned char *tmp = (unsigned char *)malloc(row);
    if (px == NULL || tmp == NULL)
        fail("out of memory for output image");

    glReadPixels(0, 0, IMG_W, IMG_H, GL_RGBA, GL_UNSIGNED_BYTE, px);
    checkGl("glReadPixels");

    /* glReadPixels отдает строки снизу вверх — переворачиваем */
    for (int y = 0; y < IMG_H / 2; y++) {
        memcpy(tmp, px + y * row, row);
        memcpy(px + y * row, px + (size_t)(IMG_H - 1 - y) * row, row);
        memcpy(px + (size_t)(IMG_H - 1 - y) * row, tmp, row);
    }

    writeLE32(stdout, IMG_W);
    writeLE32(stdout, IMG_H);
    if (fwrite(px, 1, pxBytes, stdout) != pxBytes)
        fail("failed to write output image");
    fflush(stdout);
    free(px);
    free(tmp);
}

/* ---------- разбор входного скрипта ---------- */

enum {
    CMD_LEFT, CMD_RIGHT, CMD_FORWARD, CMD_BACK, CMD_UP, CMD_DOWN,
    CMD_YAW, CMD_PITCH, CMD_SHOOT, CMD_TIME
};

struct Cmd {
    int kind;
    double val;
};

static int parseScript(char *line, struct Cmd *cmds, int maxCmds)
{
    int n = 0;
    char *tok = strtok(line, ";\n\r\t ");
    while (tok != NULL) {
        char *comma = strchr(tok, ',');
        if (comma == NULL)
            failf("invalid command '%s' (expected name,value)", tok);
        *comma = '\0';
        const char *name = tok;
        char *endp = NULL;
        double val = strtod(comma + 1, &endp);
        if (endp == comma + 1)
            failf("invalid value in command '%s'", name);
        int kind;
        if      (!strcmp(name, "left"))    kind = CMD_LEFT;
        else if (!strcmp(name, "right"))   kind = CMD_RIGHT;
        else if (!strcmp(name, "forward")) kind = CMD_FORWARD;
        else if (!strcmp(name, "back"))    kind = CMD_BACK;
        else if (!strcmp(name, "up"))      kind = CMD_UP;
        else if (!strcmp(name, "down"))    kind = CMD_DOWN;
        else if (!strcmp(name, "yaw"))     kind = CMD_YAW;
        else if (!strcmp(name, "pitch"))   kind = CMD_PITCH;
        else if (!strcmp(name, "shoot"))   kind = CMD_SHOOT;
        else if (!strcmp(name, "time"))    kind = CMD_TIME;
        else
            failf("unknown command '%s'", name);
        if (n >= maxCmds)
            fail("too many commands");
        cmds[n].kind = kind;
        cmds[n].val = val;
        n++;
        tok = strtok(NULL, ";\n\r\t ");
    }
    return n;
}

/* ---------- освобождение ресурсов ---------- */

static void cleanup(void)
{
    if (g_interop) {
        if (g_vboRes != NULL)
            cudaGraphicsUnregisterResource(g_vboRes);
        if (g_pboRes != NULL)
            cudaGraphicsUnregisterResource(g_pboRes);
    }
    cudaFree(g_dPosA);
    cudaFree(g_dPosB);
    cudaFree(g_dVel);
    cudaFree(g_dField);
    free(g_hPos);
    free(g_hField);
    if (g_dpy != NULL) {
        eglMakeCurrent(g_dpy, NULL, NULL, NULL);
        eglTerminate(g_dpy);
    }
    if (g_eglLib != NULL)
        dlclose(g_eglLib);
}

int main(void)
{
    char line[16384];
    if (fgets(line, sizeof line, stdin) == NULL)
        fail("failed to read input script");

    struct Cmd cmds[MAX_CMD];
    int ncmd = parseScript(line, cmds, MAX_CMD);

    initEgl();
    initGl();
    initCuda();

    /* начальное состояние камеры: снаружи куба, смотрит на его центр */
    g_cam = make_double3(0.0, -45.0, 22.0);
    g_yawRad = 90.0 * kDeg2Rad;
    g_pitchRad = -9.0 * kDeg2Rad;
    g_bulletActive = 0;

    for (int k = 0; k < ncmd; k++) {
        const struct Cmd *c = &cmds[k];
        double dx = cos(g_yawRad) * cos(g_pitchRad);
        double dy = sin(g_yawRad) * cos(g_pitchRad);
        double dz = sin(g_pitchRad);
        switch (c->kind) {
        case CMD_FORWARD:
            g_cam.x += dx * c->val;
            g_cam.y += dy * c->val;
            g_cam.z += dz * c->val;
            break;
        case CMD_BACK:
            g_cam.x -= dx * c->val;
            g_cam.y -= dy * c->val;
            g_cam.z -= dz * c->val;
            break;
        case CMD_LEFT:
            g_cam.x += -sin(g_yawRad) * c->val;
            g_cam.y += cos(g_yawRad) * c->val;
            break;
        case CMD_RIGHT:
            g_cam.x += sin(g_yawRad) * c->val;
            g_cam.y += -cos(g_yawRad) * c->val;
            break;
        case CMD_UP:
            g_cam.z += c->val;
            break;
        case CMD_DOWN:
            g_cam.z -= c->val;
            break;
        case CMD_YAW:
            g_yawRad += c->val * kDeg2Rad;
            break;
        case CMD_PITCH:
            g_pitchRad += c->val * kDeg2Rad;
            break;
        case CMD_SHOOT:
            g_bulletVel = make_double3(V_BUL * dx, V_BUL * dy, V_BUL * dz);
            g_bulletPos = make_double3(g_cam.x + g_bulletVel.x,
                                       g_cam.y + g_bulletVel.y,
                                       g_cam.z + g_bulletVel.z);
            g_bulletActive = 1;
            break;
        case CMD_TIME: {
            if (c->val < 0.0)
                fail("negative simulation time");
            double sd = c->val / DT + 0.5;
            if (sd > (double)MAX_STEPS)
                fail("too many simulation steps");
            simulateSteps((int)sd);
            break;
        }
        }
    }

    checkCuda(cudaMemcpy(g_hPos, g_dPosA, N_PART * sizeof(double4), cudaMemcpyDeviceToHost),
              "download positions");
    updateField();
    renderFrame();
    writeOutput();

    cleanup();
    return 0;
}
